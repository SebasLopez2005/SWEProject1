// Builds the bundled offline catalog and the Supabase catalog seed migration
// from the pinned Free Exercise DB snapshot (Unlicense).
// Usage: node scripts/build-catalog.mjs /path/to/exercises.json
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE_REVISION = 'f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5';
const EXPECTED_SHA = '5bb747e3fc658f095a60dcbf6d53c96627acdcc6ffb6fffde86f7e26995d40bf';
const NAMESPACE = '6f1b6a52-6c0e-4d64-9a1f-1f8f3c2b9e10';

const path = process.argv[2];
if (!path) throw new Error('Pass the path to exercises.json');
const raw = readFileSync(path);
const sha = createHash('sha256').update(raw).digest('hex');
if (sha !== EXPECTED_SHA) throw new Error(`Catalog hash mismatch: ${sha}`);

function uuidv5(name) {
  const ns = Buffer.from(NAMESPACE.replace(/-/g, ''), 'hex');
  const h = createHash('sha1').update(Buffer.concat([ns, Buffer.from(name, 'utf8')])).digest();
  h[6] = (h[6] & 0x0f) | 0x50;
  h[8] = (h[8] & 0x3f) | 0x80;
  const x = h.subarray(0, 16).toString('hex');
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20)}`;
}

const HOLD = /\b(plank|hold|wall sit|isometric|static|l-sit|hang|bridge hold|superman)\b/i;
function loggingType(x) {
  if (x.category === 'stretching' || x.category === 'cardio') return 'seconds';
  if (x.equipment === 'foam roll') return 'seconds';
  if (HOLD.test(x.name)) return 'seconds';
  if (x.equipment === 'body only' || x.equipment === null || x.equipment === 'bands' || x.equipment === 'exercise ball') return 'reps';
  return 'weight_reps';
}

const data = JSON.parse(raw.toString('utf8'));
const seen = new Set();
const out = data.map((x) => {
  if (seen.has(x.id)) throw new Error(`Duplicate id ${x.id}`);
  seen.add(x.id);
  return {
    id: uuidv5(`free-exercise-db:${x.id}`),
    src: x.id,
    name: x.name.trim(),
    type: loggingType(x),
    cat: x.category,
    eq: x.equipment ?? 'unknown',
    pm: [...new Set(x.primaryMuscles)],
    sm: [...new Set(x.secondaryMuscles)].filter((m) => !x.primaryMuscles.includes(m)),
    ins: x.instructions.join('\n'),
  };
});
out.sort((a, b) => a.name.localeCompare(b.name));
writeFileSync(
  new URL('../src/data/catalog.json', import.meta.url),
  JSON.stringify({ release: { sourceRevision: SOURCE_REVISION, sha256: EXPECTED_SHA, license: 'Unlicense', source: 'https://github.com/yuhonas/free-exercise-db' }, exercises: out }),
);
const esc = (s) => s.replace(/'/g, "''");
const rows = out.map((e) => `('${e.id}','${esc(e.name)}','${e.type}','${esc(e.src)}')`);
writeFileSync(
  new URL('../supabase/migrations/20261111000200_catalog_seed.sql', import.meta.url),
  `-- Generated by scripts/build-catalog.mjs from Free Exercise DB ${SOURCE_REVISION} (sha256 ${EXPECTED_SHA}, Unlicense).\n` +
    `insert into public.catalog_exercises (id, name, exercise_type, source_id) values\n${rows.join(',\n')}\non conflict (id) do update set name = excluded.name;\n`,
);
const counts = out.reduce((m, e) => ((m[e.type] = (m[e.type] ?? 0) + 1), m), {});
console.log(`Wrote ${out.length} exercises`, counts);
